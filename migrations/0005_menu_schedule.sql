CREATE TABLE IF NOT EXISTS schedule_periods (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  start_date TEXT NOT NULL,
  end_date TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  created_by_user_id INTEGER NOT NULL,
  created_by_chat_id INTEGER NOT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  closed_at TEXT,
  UNIQUE(start_date, end_date)
);

CREATE TABLE IF NOT EXISTS schedule_entries (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  period_id INTEGER NOT NULL REFERENCES schedule_periods(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL,
  chat_id INTEGER NOT NULL,
  display_name TEXT NOT NULL,
  shift_date TEXT NOT NULL,
  start_time TEXT,
  end_time TEXT,
  is_day_off INTEGER NOT NULL DEFAULT 0 CHECK (is_day_off IN (0, 1)),
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(period_id, chat_id, shift_date)
);

CREATE INDEX IF NOT EXISTS idx_schedule_periods_status
ON schedule_periods(status, start_date);

CREATE INDEX IF NOT EXISTS idx_schedule_entries_period_date
ON schedule_entries(period_id, shift_date, start_time);
