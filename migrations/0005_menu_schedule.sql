-- Переносим статус совпадающих позиций в новую редакцию.
UPDATE dishes AS current
SET availability_status = COALESCE((
      SELECT old.availability_status FROM dishes AS old
      WHERE old.id < 20000 AND lower(old.name) = lower(current.name)
      ORDER BY old.id LIMIT 1
    ), 'available'),
    limited_quantity = (
      SELECT old.limited_quantity FROM dishes AS old
      WHERE old.id < 20000 AND lower(old.name) = lower(current.name)
      ORDER BY old.id LIMIT 1
    ),
    expected_at = (
      SELECT old.expected_at FROM dishes AS old
      WHERE old.id < 20000 AND lower(old.name) = lower(current.name)
      ORDER BY old.id LIMIT 1
    ),
    is_stopped = CASE WHEN COALESCE((
      SELECT old.availability_status FROM dishes AS old
      WHERE old.id < 20000 AND lower(old.name) = lower(current.name)
      ORDER BY old.id LIMIT 1
    ), 'available') = 'stopped' THEN 1 ELSE 0 END
WHERE current.id >= 20000;

